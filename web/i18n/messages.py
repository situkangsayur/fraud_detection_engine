def build(idx):
    out = {}
    for key, pair in M.items():
        cur = out
        parts = key.split('.')
        for p in parts[:-1]:
            nxt = cur.setdefault(p, {})
            if not isinstance(nxt, dict):
                raise SystemExit(f"key collision: {key} (prefix is a leaf)")
            cur = nxt
        if isinstance(cur.get(parts[-1]), dict):
            raise SystemExit(f"key collision: {key} (leaf is a prefix)")
        cur[parts[-1]] = pair[idx]
    return out

def check_syntax():
    bad = [k for k, (a, b) in M.items() for s in (a, b) if re.search(r"[@|]", s) or re.search(r"\{(?![a-z]+\})", s)]
    if bad:
        raise SystemExit(f"vue-i18n special characters in: {bad}")

def used_keys(root):
    keys = set()
    for d, _, files in os.walk(os.path.join(root, 'app')):
        for f in files:
            if f.endswith(('.vue', '.ts')):
                keys |= set(re.findall(r"\bt\(['`]([a-zA-Z0-9_.]+)['`]", open(os.path.join(d, f), encoding='utf8').read()))
    return keys

if __name__ == '__main__':
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    check_syntax()
    missing = sorted(k for k in used_keys(root) if k not in M)
    if '--check' in sys.argv:
        if missing:
            print('missing i18n keys:\n  ' + '\n  '.join(missing))
            sys.exit(1)
        print(f'i18n OK: {len(M)} messages, all used keys defined')
        sys.exit(0)
    for idx, code in ((0, 'id'), (1, 'en')):
        with open(os.path.join(root, 'i18n', 'locales', f'{code}.json'), 'w', encoding='utf8') as fh:
            json.dump(build(idx), fh, ensure_ascii=False, indent=2)
            fh.write('\n')
    print(f'wrote {len(M)} messages; missing: {missing}')
